from fastapi import APIRouter, Request, Response
from pydantic import BaseModel
from typing import Optional
from uuid import uuid4
from agents.orchestrator import run_orchestrator
from kapruka_mcp.rate_limiter import get_rate_limit_status
from kapruka_mcp.tools.get_product import get_product
from utils.product_parser import extract_single_product
from api.middleware.auth import get_or_create_session
from utils.logger import get_logger

log = get_logger("ChatRoute")
router = APIRouter()


class ChatRequest(BaseModel):
    message:  str
    chat_id:  Optional[str] = None   # unique per chat session, generated by frontend


@router.post("/")
async def chat(body: ChatRequest, request: Request, response: Response):
    if not body.message.strip():
        return {"error": "message is required"}, 400

    user_id     = get_or_create_session(request, response)
    auth_header = request.headers.get("Authorization", "")
    log.info(
        f"CHAT AUTH | has_authorization={bool(auth_header)} | "
        f"is_bearer={auth_header.startswith('Bearer ')} | session={user_id}"
    )

    message = body.message.strip()

    # Each chat gets its own session_id = user_id + chat_id
    # This means history is scoped per chat, profile is shared across all chats
    chat_id    = body.chat_id or str(uuid4())
    session_id = f"{user_id}_{chat_id}"

    # ── Product detail fetch for modal ───────────────────────────────────
    if message.startswith("__get_product_detail__:"):
        parts      = message.split(":", 2)
        product_id = parts[1].strip() if len(parts) > 1 else ""
        if product_id:
            try:
                result = await get_product(product_id=product_id, currency="LKR")
                parsed = extract_single_product(result)
                return {
                    "reply":      "",
                    "agent":      "discovery",
                    "products":   [parsed] if parsed else [],
                    "session_id": session_id,
                    "chat_id":    chat_id,
                    "rate_limits": get_rate_limit_status(),
                }
            except Exception as e:
                log.error(f"Product detail fetch failed: {e}")
                return {"reply": "", "agent": "discovery", "products": [],
                        "session_id": session_id, "chat_id": chat_id,
                        "rate_limits": get_rate_limit_status()}

    log.info(f"Chat | session={session_id} | chat={chat_id} | msg={message[:80]}")
    result = await run_orchestrator(session_id, message)
    return {
        **result,
        "session_id":  session_id,
        "chat_id":     chat_id,
        "rate_limits": get_rate_limit_status(),
    }


@router.get("/status")
async def status(request: Request, response: Response):
    user_id = get_or_create_session(request, response)
    return {"status": "ok", "session_id": user_id, "rate_limits": get_rate_limit_status()}