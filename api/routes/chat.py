import asyncio
from typing import Optional
from uuid import UUID, uuid4

from fastapi import APIRouter, BackgroundTasks, HTTPException, Request, Response
from pydantic import BaseModel

from agents.orchestrator import run_orchestrator, post_turn
from db.thread_repository import touch_thread, set_title, delete_thread
from graph import runs
from graph.history import (
    NothingToEdit, StaleEdit, EditBlocked, rewind_to_message, discard_unfinished_turn,
)
from kapruka_mcp.rate_limiter import get_rate_limit_status
from kapruka_mcp.tools.get_product import get_product
from utils.product_parser import extract_single_product
from api.middleware.auth import get_or_create_session
from utils.logger import get_logger

log = get_logger("ChatRoute")
router = APIRouter()


class ChatRequest(BaseModel):
    message: str
    chat_id: Optional[str] = None       # new UUID per chat, generated by the UI
    # Edit: re-run from just before the N-th user message (0-based) with this new text.
    edit_human_index: Optional[int] = None
    edit_original: Optional[str] = None     # what the UI thinks it is editing (staleness check)


class ChatRef(BaseModel):
    chat_id: str


def _valid_chat_id(chat_id: str) -> str:
    try:
        return str(UUID(str(chat_id)))
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid chat_id")


def _ids(request: Request, response: Response, chat_id: str):
    """Identity comes from the signed JWT only; chat_id just selects the thread."""
    user_id = get_or_create_session(request, response)
    return user_id, f"{user_id}_{_valid_chat_id(chat_id)}"


def _title(message: str) -> str:
    one_line = " ".join(message.split())
    return one_line if len(one_line) <= 60 else one_line[:57] + "..."


@router.post("/")
async def chat(body: ChatRequest, request: Request, response: Response,
               background: BackgroundTasks):
    message = body.message.strip()
    if not message:
        raise HTTPException(status_code=400, detail="message is required")

    chat_id = _valid_chat_id(body.chat_id) if body.chat_id else str(uuid4())
    user_id, session_id = _ids(request, response, chat_id)
    graph = request.app.state.graph

    # Product detail for the modal: direct MCP call, bypasses the graph
    if message.startswith("__get_product_detail__:"):
        parts = message.split(":", 2)
        product_id = parts[1].strip() if len(parts) > 1 else ""
        products = []
        if product_id:
            try:
                parsed = extract_single_product(
                    await get_product(product_id=product_id, currency="LKR"))
                products = [parsed] if parsed else []
            except Exception as e:
                log.error(f"Product detail fetch failed: {e}")
        return {"reply": "", "agent": "discovery", "products": products,
                "session_id": session_id, "chat_id": chat_id,
                "rate_limits": get_rate_limit_status()}

    if runs.is_running(session_id):
        raise HTTPException(status_code=409,
                            detail="A reply is already being generated in this chat.")

    # Edit = time travel to just before that message, then run the new text as a normal turn.
    if body.edit_human_index is not None:
        try:
            await rewind_to_message(graph, session_id, body.edit_human_index,
                                    expected=body.edit_original)
        except NothingToEdit as e:
            raise HTTPException(status_code=404, detail=str(e))
        except (EditBlocked, StaleEdit) as e:
            raise HTTPException(status_code=409, detail=str(e))

    await touch_thread(user_id, chat_id, _title(message))   # sidebar entry; first message sets the title
    if body.edit_human_index == 0:
        await set_title(user_id, chat_id, _title(message))

    log.info(f"Chat | session={session_id} | msg={message[:80]}"
             f"{' | EDIT #' + str(body.edit_human_index) if body.edit_human_index is not None else ''}")

    # Run as a task so /stop can cancel it. asyncio.wait never re-raises the task's own error.
    task = asyncio.create_task(run_orchestrator(graph, session_id, message))
    runs.register(session_id, task)
    try:
        await asyncio.wait({task})
    except asyncio.CancelledError:          # the HTTP request itself was cancelled
        task.cancel()
        raise
    finally:
        runs.unregister(session_id, task)

    if task.cancelled():                    # the user pressed Stop
        try:
            out = await discard_unfinished_turn(graph, session_id)
            if out and out.get("empty"):
                await delete_thread(user_id, chat_id)   # a stopped first message leaves no chat behind
        except Exception as e:
            log.warning(f"Could not discard the stopped turn: {e}")
        return {"stopped": True, "reply": "", "agent": None, "products": [],
                "removed_message": message, "session_id": session_id,
                "chat_id": chat_id, "rate_limits": get_rate_limit_status()}

    result = task.result()                  # re-raises -> the app's generic error handler
    background.add_task(post_turn, session_id, user_id, message,
                        result["reply"], result["agent"])
    return {**result, "session_id": session_id, "chat_id": chat_id,
            "rate_limits": get_rate_limit_status()}


@router.post("/stop")
async def stop(body: ChatRef, request: Request, response: Response):
    """Cancel the reply being generated. The pending /api/chat/ request then returns stopped=true."""
    _, session_id = _ids(request, response, body.chat_id)
    return {"result": runs.request_stop(session_id)}


@router.get("/status")
async def status(request: Request, response: Response):
    user_id = get_or_create_session(request, response)
    return {"status": "ok", "session_id": user_id, "rate_limits": get_rate_limit_status()}
